#!/usr/bin/env python3
"""Audit the proposed JSON v3 representation without changing product saves.

Usage: check-parameter-v3-reference.py SOURCE-ROOT COLORSCREEN-BINARY
Runs over the same checked-in .par inputs as check-parameter-v2-corpus.py,
then checks nondefault, inactive and MTF provenance samples and fail-closed
validation of future fields and nonrepresentable selection/capture-group edits.
"""

from __future__ import annotations

from copy import deepcopy
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile


def check_raises(callback, msg: str) -> None:
    try:
        callback()
    except ValueError:
        return
    raise AssertionError(msg)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: check-parameter-v3-reference.py ROOT COLORSCREEN")
        return 2
    root = Path(sys.argv[1]).resolve()
    cli = Path(sys.argv[2]).resolve()
    loader = importlib.util.spec_from_file_location("v3reference", root / "testsuite/parameter-json-v3-reference.py")
    if not loader or not loader.loader:
        raise RuntimeError("cannot load v3 reference")
    module = importlib.util.module_from_spec(loader)
    loader.loader.exec_module(module)

    # Load only source fixtures, not outputs generated by concurrent in-tree
    # make check. Tests may run before or after parameter-archive-cli.test.
    sources = sorted(
        path for directory in (root / "testsuite", root / "examples")
        for path in directory.rglob("*.par")
        if path.is_file() and not (
            directory.name == "testsuite" and path.name.startswith(("out-", "out2-"))
        )
    )
    if len(sources) < 100:
        raise AssertionError(f"missing .par fixtures: {len(sources)}")

    with tempfile.TemporaryDirectory(prefix="colorscreen-v3-reference-") as tmp:
        v2_path = Path(tmp) / "input.cspar"
        v2_values = []
        for i, source in enumerate(sources):
            v2_path.unlink(missing_ok=True)
            result = subprocess.run([str(cli), "adjust-par", str(source), "--out", str(v2_path)],
                                    capture_output=True, timeout=90, text=True, errors="replace")
            if result.returncode:
                raise AssertionError(f"{source.relative_to(root)}: {result.stderr[-1000:]}")
            doc = json.loads(v2_path.read_text(encoding="utf-8"))
            if i == 0:
                seed = deepcopy(doc)
            v3 = module.upgrade_v2(doc)
            original_v3 = deepcopy(v3)
            restored = module.downgrade_v3(v3)
            if restored != doc or v3 != original_v3:
                raise AssertionError(f"v2 -> v3 -> v2 not equivalent: {source.relative_to(root)}")
            v2_values.append((source, doc))
            if (i + 1) % 25 == 0:
                print(f"# Checked {i + 1}/{len(sources)} v2-v3 reference pairs", flush=True)

    assert len(v2_values) == len(sources)
    print(f"# {len(sources)} legacy fixtures passed complete JSON tree identity")

    # Transform real, typed valid v2 defaults with independent nondefault
    # settings. The reference translator must preserve *all* inactive knobs.
    rich = deepcopy(seed)
    rich["capture"].update({
        "gamma": 2.4, "scan_rotation_quarter_turns": 3, "scan_mirror": True,
        "scan_crop": {"enabled": True, "rect": [-20, 4, 16000, 12000]},
        "image_area": {"enabled": True, "rect": [120, 85, 14300, 10200]},
        "scan_exposure": 1.4, "dark_point": 0.042,
    })
    rich["process"]["strip_widths"] = {"red": 0, "green": 0.37}
    rich["geometry"]["final_angle"] = 108.375
    rich["geometry"]["final_ratio"] = 0.803158
    rich["sharpness"].update({"unsharp_radius": 3.21,
                               "richardson_lucy_iterations": 0,
                               "richardson_lucy_sigma": 2.72})
    rich["profile"]["spots"] = [[10.23, 21.41], [98.12, 7.5]]
    measurements = []
    for i in range(4):
        measurements.append({
            "channel": ["red", "green", "blue", "none"][i],
            "image_layer": bool(i % 2),
            "wavelength_nm": 450 + 35 * i,
            "same_capture": i in (1, 2),
            "name": f"focus Ångström {i}",
            "source_filename": [r"C:\\samples\\calibration\\img.tif", "../relative/edge.tif"][i % 2],
            "source_dimensions": [10000, 7200] if i != 3 else [-1, 0],
            "roi": [100, 150, 300, 250] if i != 3 else [99, 3, -1, -1],
            "edge": [[1.2, 2.3], [8.5, 9.7]],
            "edge_quality": [4.2, 0.08, 0.7, 35.0, 0.93],
            "samples": [[0.05, 92.0, 0.5], [0.2, 41.0, 2.0]],
        })
    rich["sharpness"]["mtf"]["measurements"] = measurements
    rich["sharpness"]["mtf"]["selected_measurement"] = 2
    v3 = module.upgrade_v2(rich)
    assert v3["capture"]["linearization"] == {"mode": "power", "exponent": 2.4}
    assert v3["capture"]["bounds"]["object_crop"]["x_px"] == -20
    assert v3["process"]["screen"]["strip_widths"]["red"] == {"mode": "automatic"}
    assert v3["calibration"]["capture"]["mtf"]["selected_measurement_id"] == "measurement-000003"
    assert [m["capture_group_id"] for m in v3["calibration"]["capture"]["mtf"]["measurements"]] == [
        "capture-000001", "capture-000001", "capture-000001", "capture-000002"]
    assert module.downgrade_v3(v3) == rich
    print("# Rich nondefault capture/MTF/geometry/inactive-settings conversion passed")

    # A v3 editor may change order within a capture group. Selection and
    # capture relationship must still refer to stable IDs, not indexes.
    curves = v3["calibration"]["capture"]["mtf"]["measurements"]
    curves[0], curves[2] = curves[2], curves[0]
    reordered = module.downgrade_v3(v3)
    assert reordered["sharpness"]["mtf"]["selected_measurement"] == 0
    assert [m["name"] for m in reordered["sharpness"]["mtf"]["measurements"]][:3] == [
        "focus Ångström 2", "focus Ångström 1", "focus Ångström 0"]

    # But v2 cannot represent *discontiguous* capture groups. Such a
    # downgrade must fail visibly rather than silently change grouping.
    curves[1], curves[3] = curves[3], curves[1]
    check_raises(lambda: module.downgrade_v3(v3), "split capture group silently changed")
    curves[1], curves[3] = curves[3], curves[1]
    curves[1]["id"] = curves[0]["id"]
    check_raises(lambda: module.downgrade_v3(v3), "duplicate MTF IDs accepted")
    curves[1]["id"] = "measurement-000002"
    v3["calibration"]["capture"]["mtf"]["selected_measurement_id"] = "missing-id"
    check_raises(lambda: module.downgrade_v3(v3), "dangling MTF selection accepted")
    print("# ID stable-reordering and grouping/dangling-ID safeguards passed")

    invalid = deepcopy(seed)
    invalid["capture"]["future_display_gamma"] = 2.2
    check_raises(lambda: module.upgrade_v2(invalid), "unknown capture field silently lost")
    invalid = deepcopy(seed)
    invalid["process"]["contact_copy"]["unknown_future_spectrum"] = 99
    check_raises(lambda: module.upgrade_v2(invalid), "unknown deep field silently lost")
    invalid = deepcopy(seed)
    invalid["correction_grids"]["tiles"]["unrecognized"] = [1, 2]
    check_raises(lambda: module.upgrade_v2(invalid), "unknown tile field silently lost")
    invalid = deepcopy(v3)
    invalid["color"]["viewing"]["display_profile"] = "sRGB"
    check_raises(lambda: module.downgrade_v3(invalid), "display profile silently persisted")
    print("# Unknown-field traps passed")

    # Empty source filenames mean missing provenance, not a relative path
    # naming the current parameter-file directory.
    no_source = deepcopy(rich)
    no_source["sharpness"]["mtf"]["measurements"][1]["source_filename"] = ""
    upgraded_no_source = module.upgrade_v2(no_source)
    assert upgraded_no_source["calibration"]["capture"]["mtf"]["measurements"][1]["source"]["path"] is None
    assert module.downgrade_v3(upgraded_no_source) == no_source

    def malformed_v3(mutator):
        candidate = module.upgrade_v2(rich)
        mutator(candidate)
        check_raises(lambda: module.downgrade_v3(candidate),
                     "malformed v3 provenance/status accepted")

    def wrong_base(doc):
        # The first source is Windows-absolute even when validated on Unix.
        doc["calibration"]["capture"]["mtf"]["measurements"][0]["source"]["path"]["base"] = "parameter_file"
    malformed_v3(wrong_base)

    def empty_path(doc):
        doc["calibration"]["capture"]["mtf"]["measurements"][0]["source"]["path"]["value"] = ""
    malformed_v3(empty_path)

    def wrong_status(doc):
        doc["calibration"]["capture"]["mtf"]["measurements"][0]["source"]["roi"]["width_px"] = 0
    malformed_v3(wrong_status)

    def wrong_legacy_flag(doc):
        doc["calibration"]["capture"]["mtf"]["legacy_first_same_capture"] = "false"
    malformed_v3(wrong_legacy_flag)

    def bad_crop(doc):
        doc["capture"]["bounds"]["photograph"]["width_px"] = 0
    malformed_v3(bad_crop)

    corrupt = deepcopy(rich)
    corrupt["sharpness"]["mtf"]["measurements"][0]["same_capture"] = "false"
    check_raises(lambda: module.upgrade_v2(corrupt),
                 "nonboolean MTF same_capture accepted")
    print("# Source-path, availability, crop, and migration-flag integrity passed")

    # Saving the parameter document in another directory must not change
    # which image each relative measurement path refers to.
    original = module.upgrade_v2(rich)
    rebased = module.rebase_v3_source_paths(
        original, "/srv/photos/session/state.cspar", "/srv/exports/new.cspar")
    srcs = original["calibration"]["capture"]["mtf"]["measurements"]
    moved = rebased["calibration"]["capture"]["mtf"]["measurements"]
    assert moved[0]["source"]["path"] == srcs[0]["source"]["path"]
    assert moved[1]["source"]["path"] == {
        "base": "parameter_file", "value": "../photos/relative/edge.tif"}
    assert original["calibration"]["capture"]["mtf"]["measurements"] == srcs

    import ntpath
    windows_old = r"C:\archive\session\params.cspar"
    windows_new = r"C:\archive\exports\params.cspar"
    moved_windows = module.rebase_v3_source_paths(original, windows_old, windows_new)
    win_path = moved_windows["calibration"]["capture"]["mtf"]["measurements"][1]["source"]["path"]
    assert ntpath.normpath(ntpath.join(ntpath.dirname(windows_new), win_path["value"])) == (
        r"C:\archive\relative\edge.tif")
    assert win_path["base"] == "parameter_file"
    across_volumes = module.rebase_v3_source_paths(
        original, windows_old, r"D:\archive\params.cspar")
    different = across_volumes["calibration"]["capture"]["mtf"]["measurements"][1]["source"]["path"]
    assert different == {"base": "absolute", "value": r"C:\archive\relative\edge.tif"}
    assert module.rebase_v3_source_paths(upgraded_no_source,
        "/srv/photos/session/state.cspar", "/srv/exports/new.cspar")[
            "calibration"]["capture"]["mtf"]["measurements"][1]["source"]["path"] is None

    check_raises(lambda: module.rebase_v3_source_paths(original,
                 "session/state.cspar", "/srv/exports/new.cspar"),
                 "relative document path accepted for Save As")
    invalid_rebase = deepcopy(original)
    invalid_rebase["calibration"]["capture"]["mtf"]["measurements"][1]["source"]["path"]["base"] = "absolute"
    check_raises(lambda: module.rebase_v3_source_paths(invalid_rebase,
                 "/srv/photos/session/state.cspar", "/srv/exports/new.cspar"),
                 "contradictory path base accepted for Save As")
    print("# Reference-only POSIX/Windows Save As path rebasing passed")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (AssertionError, OSError, ValueError, subprocess.TimeoutExpired) as exc:
        # Preserve the failing line and actual platform path operation.
        # An unlabelled assert has an empty message on Windows, which
        # otherwise makes a regression impossible to diagnose from CI logs.
        import traceback
        traceback.print_exc(file=sys.stderr)
        print(f"# JSON v3 reference validation failure: {exc}", file=sys.stderr)
        raise SystemExit(1)
